// Reviewed individual OSM courts, joined explicitly to City facility identities.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {projectPoint} from './build-open-data.mjs';
const root=fileURLToPath(new URL('..',import.meta.url));
export function tennisCourts(snapshot,review,geo,facilities) {
  const elements=new Map(snapshot.elements.map((e)=>[e.id,e]));
  const records=[],seen=new Set(),audit=[];
  for(const group of review.groups) {
    const listings=facilities.records.filter((r)=>r.kind==='tennis'&&r.locationId===group.cityLocationId);
    if(!listings.length)throw new Error(`Missing City tennis facility ${group.cityLocationId}`);
    for(const id of group.ways) {
      if(seen.has(id))throw new Error(`Duplicate reviewed court ${id}`);seen.add(id);
      const e=elements.get(id);
      if(!e||e.type!=='way'||e.tags.sport!=='tennis'||e.tags.leisure!=='pitch'||e.tags.access==='private')throw new Error(`Unverified individual tennis court ${id}`);
      const points=e.geometry.map((p)=>projectPoint({type:'Point',coordinates:[p.lon,p.lat]},geo.frame));
      if(points.some((p)=>!p)){audit.push({id,reason:'outside-detail-frame'});continue;}
      const first=points[0],last=points.at(-1);
      if(points.length!==5||Math.hypot(first.x-last.x,first.z-last.z)>.05)throw new Error(`Court ${id} is not a closed quadrilateral`);
      const ps=points.slice(0,4),edges=ps.map((p,i)=>{const q=ps[(i+1)%4];return {x:q.x-p.x,z:q.z-p.z,length:Math.hypot(q.x-p.x,q.z-p.z)};});
      const longest=edges.reduce((a,b)=>a.length>b.length?a:b),length=(edges[0].length+edges[2].length)/2,width=(edges[1].length+edges[3].length)/2;
      const mappedLength=Math.max(length,width),mappedWidth=Math.min(length,width);
      if(Math.abs(mappedLength/23.77-1)>.08||Math.abs(mappedWidth/10.97-1)>.05||edges.some((a,i)=>{const b=edges[(i+1)%4];return Math.abs((a.x*b.x+a.z*b.z)/(a.length*b.length))>.05;})||Math.abs(edges[0].length-edges[2].length)>.5||Math.abs(edges[1].length-edges[3].length)>.5)throw new Error(`Court ${id} has unsupported dimensions/shape`);
      records.push({id:`osm-way:${id}`,cityLocationId:group.cityLocationId,listingIds:listings.map((r)=>r.id),x:ps.reduce((n,p)=>n+p.x,0)/4,z:ps.reduce((n,p)=>n+p.z,0)/4,yaw:Math.atan2(longest.x,longest.z),mappedLength,mappedWidth,length:23.77,width:10.97,colour:group.colours==='blue-green'||group.blueWays.includes(id)?'blue-green':'asphalt',evidence:'OSM footprint + City 2025 aerial review',reviewedAt:group.reviewedAt});
    }
    const actual=records.filter((r)=>r.cityLocationId===group.cityLocationId).length;
    if(listings.some((r)=>r.facts.Courts!==actual))audit.push({cityLocationId:group.cityLocationId,mappedCourts:actual,sourceListings:listings.map((r)=>({id:r.id,courts:r.facts.Courts,access:r.facts['Access type']})),notes:group.notes});
  }
  const pads=(review.pads||[]).map((pad)=>{
    const coordinates=pad.osmWay?elements.get(pad.osmWay).geometry.map((p)=>[p.lon,p.lat]):pad.pixels.map(([x,y])=>{
      const a=pad.aerial,e=a.extent,mx=e.xmin+x/a.width*(e.xmax-e.xmin),my=e.ymax-y/a.height*(e.ymax-e.ymin);
      return [mx/6378137*180/Math.PI,(2*Math.atan(Math.exp(my/6378137))-Math.PI/2)*180/Math.PI];
    });
    const points=coordinates.map((coordinates)=>projectPoint({type:'Point',coordinates},geo.frame));
    if(points.some((p)=>!p))throw new Error(`Pad ${pad.id} crosses detail boundary`);
    if(Math.hypot(points[0].x-points.at(-1).x,points[0].z-points.at(-1).z)<.1)points.pop();
    return {id:pad.id,cityLocationId:pad.cityLocationId,ring:points.map((p)=>[p.x,p.z]),x:points.reduce((s,p)=>s+p.x,0)/points.length,z:points.reduce((s,p)=>s+p.z,0)/points.length,colour:pad.colour,evidence:pad.evidence};
  });
  return {source:snapshot.source,reviewSource:'tools/data/tennis-review-20261028.json',audit,pads,records:records.sort((a,b)=>a.id.localeCompare(b.id))};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const context={window:{CITY:{}}};
  for(const name of ['toronto-geodata','toronto-city-facilities'])vm.runInNewContext(fs.readFileSync(path.join(root,`js/${name}.js`),'utf8'),context);
  const read=(file)=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
  const data=tennisCourts(read('tools/data/sports-footprints-20261023.json'),read('tools/data/tennis-review-20261028.json'),context.window.CITY.GEO,context.window.CITY.CITY_FACILITIES);
  fs.writeFileSync(path.join(root,'js/toronto-tennis.js'),'// GENERATED by tools/build-tennis.mjs. Reviewed mapped courts; facility access remains in City listings.\n(function(){window.CITY.TENNIS='+JSON.stringify(data)+';})();\n');
  console.log(`[tennis] ${data.records.length} reviewed courts; ${data.audit.length} source disagreements`);
}
