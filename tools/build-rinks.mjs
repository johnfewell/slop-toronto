const root=fileURLToPath(new URL('..',import.meta.url));
function pixelPoint(a,[x,y]) {
  const e=a.extent,mx=e.xmin+x/a.width*(e.xmax-e.xmin),my=e.ymax-y/a.height*(e.ymax-e.ymin);
  return [mx/6378137*180/Math.PI,(2*Math.atan(Math.exp(my/6378137))-Math.PI/2)*180/Math.PI];
}
export function rinkFootprints(snapshot,review,geo,facilities) {
  const inventory=facilities.records.filter((r)=>r.kind==='rink'),seen=new Set(),records=[],audit=[];
  for(const f of snapshot.features) {
    const a=f.properties,id=String(a.ASSET_ID),listing=inventory.find((r)=>r.assetId===id),check=review.records.find((r)=>r.assetId===id);
    if(!listing||!check||seen.has(id))throw new Error(`Unmatched/duplicate rink ${id}`);seen.add(id);
    if(a.EXPIRY_DATE&&a.EXPIRY_DATE<Date.parse('2026-10-28'))throw new Error(`Expired rink footprint ${id}`);
    const parts=f.geometry.type==='Polygon'?[f.geometry.coordinates]:f.geometry.type==='MultiPolygon'?f.geometry.coordinates:null;
    if(!parts)throw new Error(`Rink ${id} requires polygon geometry`);
    const polygons=parts.map((rings)=>{
      const ps=rings.map((ring)=>{
        const points=ring.map((coordinates)=>projectPoint({type:'Point',coordinates},geo.frame));
        if(points.some((p)=>!p))throw new Error(`Rink ${id} crosses detail boundary`);
        const out=points.map((p)=>[p.x,p.z]).filter((p,i,all)=>i===0||p[0]!==all[i-1][0]||p[1]!==all[i-1][1]);
        if(out[0][0]===out.at(-1)[0]&&out[0][1]===out.at(-1)[1])out.pop();
        if(out.length<3)throw new Error(`Degenerate rink ${id}`);return out;
      });
      return {outer:ps[0],holes:ps.slice(1)};
    });
    const gate=check.gatePixel?projectPoint({type:'Point',coordinates:pixelPoint(check.aerial,check.gatePixel)},geo.frame):null;
    const sourceBoards=listing.facts.Boards==='Yes';
    if(sourceBoards!==check.boards)audit.push({id,kind:'boards',source:listing.facts.Boards,rendered:check.boards,evidence:check.notes});
    records.push({id:`city-rink:${id}`,assetId:id,gisId:a.GIS_ID,objectId:a.OBJECTID,name:listing.name,parentName:listing.parentName,type:listing.type,x:listing.x,z:listing.z,polygons,boards:check.boards,gate,appearance:check.appearance,sourceDimensions:listing.dimensions,sourceFacts:listing.facts,sourceModifiedAt:a.LASTMODIFIED_DATE,reviewedAt:check.reviewedAt});
  }
  if(seen.size!==inventory.length)throw new Error('Incomplete rink geometry snapshot');
  return {source:snapshot.source,reviewSource:'tools/data/rink-review-20261028.json',audit,records:records.sort((a,b)=>a.id.localeCompare(b.id))};
}
// The records a frame adds to the detail map's (CITY.RINKS): the frame's inventory is checked whole (the detail map's snapshot and
// review again, projected with the frame's box), and the ones the detail map already holds are left out
export function frameRinks(read,frame,GEO,facilities,have) {
  const snap=read(`tools/data/rink-footprints-20261126-${frame}.json`),review=read(`tools/data/rink-review-20261126-${frame}.json`);
  const all=rinkFootprints({...snap,features:[...read('tools/data/rink-footprints-20261028.json').features,...snap.features]},{...review,records:[...read('tools/data/rink-review-20261028.json').records,...review.records]},GEO,facilities);
  const known=new Set(have.records.map((r)=>r.assetId)),records=all.records.filter((r)=>!known.has(r.assetId));
  const added=new Set(records.map((r)=>r.assetId)),audit=all.audit.filter((a)=>added.has(a.id));
  return {source:snap.source,reviewSource:`tools/data/rink-review-20261126-${frame}.json`,audit,records};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const {frame}=frameArgs(),read=(p)=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
  const {GEO}=await loadFrameGeo(frame),context={window:{CITY:{}}};
  vm.runInNewContext(fs.readFileSync(layerFile(frame,'toronto-city-facilities.js'),'utf8'),context);
  const facilities=context.window.CITY.CITY_FACILITIES;
  if(frame==='detail') {
    const data=rinkFootprints(read('tools/data/rink-footprints-20261028.json'),read('tools/data/rink-review-20261028.json'),GEO,facilities);
    fs.writeFileSync(path.join(root,'js/toronto-rinks.js'),'// GENERATED by tools/build-rinks.mjs. City polygon assets, not rectangles inferred from facility points.\n(function(){window.CITY.RINKS='+JSON.stringify(data)+';})();\n');
    console.log(`[rinks] ${data.records.length} City footprint identities; ${data.audit.length} physical/source flag disagreements`);
  } else {
    // A frame beyond the detail map: the detail map's records (js/toronto-rinks.js) are not repeated; this frame's file adds the
    // rest of the frame's inventory to them, from its own dated snapshot and aerial review (tools/data/rink-*-20261126-<frame>.json)
    const detail={window:{CITY:{}}};vm.runInNewContext(fs.readFileSync(path.join(root,'js/toronto-rinks.js'),'utf8'),detail);
    const have=detail.window.CITY.RINKS,data=frameRinks(read,frame,GEO,facilities,have);
    fs.writeFileSync(layerFile(frame,'toronto-rinks.js'),`// GENERATED by tools/build-rinks.mjs --frame ${frame}. The City rink polygons of the ${frame} map beyond the detail map's, added to CITY.RINKS (js/toronto-rinks.js).\n(function(){const R=window.CITY.RINKS;R.records.push(...${JSON.stringify(data.records)});R.audit.push(...${JSON.stringify(data.audit)});R.frameSource=${JSON.stringify({frame,source:data.source,reviewSource:data.reviewSource,added:data.records.length})};})();\n`);
    console.log(`[rinks ${frame}] ${data.records.length} City footprints added to the detail map's ${have.records.length}; ${data.audit.length} physical/source flag disagreements`);
  }
}
