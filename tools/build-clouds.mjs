// tools/build-clouds.mjs — bundles John's three-clouds-webgpu with @takram/three-atmosphere & three-geospatial into
// js/clouds.js: one ES module importing three from the page's import map (three's dev build); three/tsl inside the bundle
// goes through vendor/clouds/tsl-struct-shim.js. The library is its r187 profile build
// (vendor/clouds/three-clouds-webgpu-0.1.0-r187.tgz, draft PR #381 "opt-in pinned Three.js r187 compatibility profile",
// qualified for three commit e27dfa95, the one explore.html pins; SHA-256 f1c8f9e6...bf9d), unpacked into
// node_modules/.cache on first build.
// usage: node tools/build-clouds.mjs
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { build } from 'esbuild';

const TGZ = 'vendor/clouds/three-clouds-webgpu-0.1.0-r187.tgz';
const UNPACKED = path.resolve('node_modules/.cache/three-clouds-webgpu-r187');
if (!process.env.CLOUDS_DIR && !fs.existsSync(path.join(UNPACKED, 'package/build/index.js'))) {
  fs.mkdirSync(UNPACKED, { recursive: true });
  execFileSync('tar', ['xzf', TGZ, '-C', UNPACKED]);
}
const CLOUDS_DIR = process.env.CLOUDS_DIR || path.join(UNPACKED, 'package');

const shim = path.resolve('vendor/clouds/tsl-struct-shim.js');
const compat = {
  name: 'compat-stubs',
  setup(b) {
    // three's dev build has no struct().layout: every three/tsl import of the bundle goes through the shim
    b.onResolve({ filter: /^three\/tsl$/ }, (args) => (args.importer === shim ? { path: 'three/tsl', external: true } : { path: shim }));
    // jsDelivr refuses three's EXRLoader from the dev branch (403): bundle npm three's copy (its three imports stay external)
    b.onResolve({ filter: /^three\/(addons|examples\/jsm)\/loaders\/EXRLoader\.js$/ }, () => ({ path: path.resolve('node_modules/three/examples/jsm/loaders/EXRLoader.js') }));
    b.onResolve({ filter: /^three\/examples\/jsm\// }, (args) => ({ path: args.path.replace('three/examples/jsm/', 'three/addons/'), external: true }));
    // the r187 build (or CLOUDS_DIR=<unpacked tarball>/package, another version for bisecting)
    b.onResolve({ filter: /^three-clouds-webgpu$/ }, () => ({ path: path.join(CLOUDS_DIR, 'build/index.js') }));
    // The page maps three to its WebGPU build, which has no WebGL classes; takram names two of them (an instanceof test
    // on a WebGL path, an unused import), so they stand in as empty classes
    b.onResolve({ filter: /^three$/ }, (args) => (args.importer === 'three-plus' ? { path: 'three', external: true } : { path: 'three-plus', namespace: 'stub' }));
    b.onLoad({ filter: /^three-plus$/, namespace: 'stub' }, () => ({
      contents: "export * from 'three'; export class WebGLCubeRenderTarget {} export class WebGLRenderer {}", loader: 'js', resolveDir: process.cwd()
    }));
    // takram reaches into three's source for two hash helpers; three/webgpu exports them as NodeUtils
    b.onResolve({ filter: /^three\/src\/nodes\/core\/NodeUtils\.js$/ }, () => ({ path: 'node-utils', namespace: 'stub' }));
    b.onLoad({ filter: /^node-utils$/, namespace: 'stub' }, () => ({
      contents: "import { NodeUtils } from 'three/webgpu'; export const hash = NodeUtils.hash; export const hashString = NodeUtils.hashString;",
      loader: 'js', resolveDir: process.cwd()
    }));
    // The WebGL postprocessing library, behind takram's WebGL effects: never constructed here, so every name it
    // exports is an empty class
    b.onResolve({ filter: /^postprocessing$/ }, () => ({ path: 'postprocessing', namespace: 'stub' }));
    b.onLoad({ filter: /^postprocessing$/, namespace: 'stub' }, () => {
      const names = ['BlendFunction', 'ClearPass', 'DepthCopyPass', 'DepthMaskMaterial', 'DepthTestStrategy', 'Effect', 'EffectAttribute', 'Pass', 'RenderPass', 'Selection', 'ShaderPass'];
      // each an extendable class whose every static property is a number (enum members such as BlendFunction.NORMAL)
      const stub = 'new Proxy(class {}, { get: (t, k) => (k in t ? t[k] : 0) })';
      return { contents: names.map((n) => `export const ${n} = ${stub};`).join('\n'), loader: 'js' };
    });
  }
};
await build({
  entryPoints: ['vendor/clouds/entry.js'],
  outfile: 'js/clouds.js',
  bundle: true,
  format: 'esm',
  target: 'es2022',
  external: ['three/webgpu', 'three/addons/*'],
  plugins: [compat],
  nodePaths: [path.resolve('node_modules')],
  banner: { js: '// js/clouds.js — GENERATED by tools/build-clouds.mjs (three-clouds-webgpu 0.1.0, r187 profile, @takram/three-atmosphere 0.19.1, @takram/three-geospatial 0.9.1; licences in vendor/clouds). Do not edit.' },
  logLevel: 'warning'
});
console.log('[clouds] wrote js/clouds.js');
