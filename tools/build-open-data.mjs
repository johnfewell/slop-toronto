// Small dated City layers, kept separate from the expensive terrain import.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
export function projectPoint(geometry, frame) {
  let coordinates = typeof geometry === 'string' ? JSON.parse(geometry) : geometry;
  if (coordinates?.type === 'MultiPoint') coordinates = coordinates.coordinates[0];
  else if (coordinates?.type === 'Point') coordinates = coordinates.coordinates;
  else throw new Error('Expected a City point geometry');
  const [lon, lat] = coordinates;
  if (!Number.isFinite(lon) || !Number.isFinite(lat) || lon < -80 || lon > -79 || lat < 43 || lat > 44) throw new Error('Invalid Toronto coordinate');
  const p = frame.projection, b = frame.detail;
  const e = (lon-p.lon0)*p.kx, n = (lat-p.lat0)*p.ky;
  const x = e*Math.cos(p.theta)-n*Math.sin(p.theta)-p.ox;
  const z = -(e*Math.sin(p.theta)+n*Math.cos(p.theta))-p.oz;
  return x > b.x0 && x < b.x1 && z > b.z0 && z < b.z1 ? {x: Math.round(x*100)/100, z: Math.round(z*100)/100} : null;
}
export function furniture(snapshot, frame) {
  const ids = new Set(), records = [];
  for (const {properties:a,geometry} of snapshot.features) {
    if (a.STATUS !== 'Existing') continue;
    if (!a.ID || ids.has(a.ID)) throw new Error(`Missing/duplicate City furniture ID: ${a.ID}`);
    ids.add(a.ID);
    const point = projectPoint(geometry, frame);
    if (point) records.push({id:a.ID, type:a.ASSETTYPE, frontage:a.FRONTINGSTREET, side:a.SIDE, address:`${a.ADDRESSNUMBERTEXT || ''} ${a.ADDRESSSTREET || ''}`.trim(), ...point});
  }
  return {source:snapshot.source, records:records.sort((a,b)=>a.id.localeCompare(b.id))};
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const context = { window: { CITY: {} } };
  vm.runInNewContext(fs.readFileSync(path.join(root,'js/toronto-geodata.js'),'utf8'),context);
  for(const [name,key] of [['benches','BENCHES'],['wayfinding','WAYFINDING']]) {
    const snapshot = JSON.parse(fs.readFileSync(path.join(root,`tools/data/${name}-20261028.json`),'utf8'));
    const data = furniture(snapshot, context.window.CITY.GEO.frame);
    fs.writeFileSync(path.join(root,`js/toronto-${name}.js`), '// GENERATED by tools/build-open-data.mjs. City Existing furniture, dated snapshot.\n(function () { window.CITY.'+key+' = '+JSON.stringify(data)+'; })();\n');
    console.log(`[openData] ${data.records.length} Existing mapped ${name}`);
  }
}
