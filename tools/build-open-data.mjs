export function projectPoint(geometry, frame) {
  let coordinates = typeof geometry === 'string' ? JSON.parse(geometry) : geometry;
  if (coordinates?.type === 'MultiPoint') coordinates = coordinates.coordinates[0];
  else if (coordinates?.type === 'Point') coordinates = coordinates.coordinates;
  else throw new Error('Expected a City point geometry');
  const [lon, lat] = coordinates;
  if (!Number.isFinite(lon) || !Number.isFinite(lat) || lon < -80 || lon > -79 || lat < 43 || lat > 44) throw new Error('Invalid Toronto coordinate');
  const p = frame.projection, b = frame.detail;
  const e = (lon-p.lon0)*p.kx, n = (lat-p.lat0)*p.ky;
  const x = e*Math.cos(p.theta)-n*Math.sin(p.theta)-p.ox;
  const z = -(e*Math.sin(p.theta)+n*Math.cos(p.theta))-p.oz;
  return x > b.x0 && x < b.x1 && z > b.z0 && z < b.z1 ? {x: Math.round(x*100)/100, z: Math.round(z*100)/100} : null;
}
export function furniture(snapshot, frame) {
  const ids = new Set(), records = [];
  for (const {properties:a,geometry} of snapshot.features) {
    if (a.STATUS !== 'Existing') continue;
    if (!a.ID || ids.has(a.ID)) throw new Error(`Missing/duplicate City furniture ID: ${a.ID}`);
    ids.add(a.ID);
    const point = projectPoint(geometry, frame);
    if (point) records.push({id:a.ID, type:a.ASSETTYPE, frontage:a.FRONTINGSTREET, side:a.SIDE, address:`${a.ADDRESSNUMBERTEXT || ''} ${a.ADDRESSSTREET || ''}`.trim(), ...point});
  }
  return {source:snapshot.source, records:records.sort((a,b)=>a.id.localeCompare(b.id))};
}
// What a City feed holds and how much of it lands in a frame: every feature, the Existing ones (the rest are
// Temporarily Removed), those inside the frame, each by asset type. Poster and publication structures keep their
// records (furniture(), above); the litter receptacles are placed from the geodata binary, so this is their audit.
export function feedCounts(snapshot, frame) {
  const byType = {}, inFrameByType = {};
  let existing = 0, removed = 0, inFrame = 0;
  for (const {properties: a, geometry} of snapshot.features) {
    if (a.STATUS !== 'Existing') { removed++; continue; }
    existing++;
    byType[a.ASSETTYPE] = (byType[a.ASSETTYPE] || 0) + 1;
    if (projectPoint(geometry, frame)) { inFrame++; inFrameByType[a.ASSETTYPE] = (inFrameByType[a.ASSETTYPE] || 0) + 1; }
  }
  return {feed: snapshot.features.length, existing, removed, inFrame, byType, inFrameByType};
}
// The two frames the page can open (explore.html): today's detail map and ?map=eglinton, which shares its projection
export function frameBoxes(detailFrame, eglintonWorld) {
  return {detail: detailFrame, eglinton: {...detailFrame, detail: eglintonWorld}};
}
export const STREET_FURNITURE = [
  {name: 'poster-structures', key: 'posters', records: true},
  {name: 'publication-structures', key: 'publications', records: true},
  {name: 'litter-receptacles', key: 'litter', records: false}
];
export function streetFurniture(snapshots, frame) {
  const out = {};
  for (const {name, key, records} of STREET_FURNITURE) {
    const counts = feedCounts(snapshots[name], frame);
    out[key] = records ? {...furniture(snapshots[name], frame), counts} : {source: snapshots[name].source, counts};
  }
  return out;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const context = { window: { CITY: {} } };
  vm.runInNewContext(fs.readFileSync(path.join(root,'js/toronto-geodata.js'),'utf8'),context);
  for(const [name,key] of [['benches','BENCHES'],['wayfinding','WAYFINDING']]) {
    const snapshot = JSON.parse(fs.readFileSync(path.join(root,`tools/data/${name}-20261028.json`),'utf8'));
    const data = furniture(snapshot, context.window.CITY.GEO.frame);
    fs.writeFileSync(path.join(root,`js/toronto-${name}.js`), '// GENERATED by tools/build-open-data.mjs. City Existing furniture, dated snapshot.\n(function () { window.CITY.'+key+' = '+JSON.stringify(data)+'; })();\n');
    console.log(`[openData] ${data.records.length} Existing mapped ${name}`);
  }
  // Street furniture in both frames: the detail map's file, and ?map=eglinton's own (js/frames/eglinton/)
  const eglintonWorld = JSON.parse(fs.readFileSync(path.join(root,'tools/frames/eglinton.json'),'utf8')).world;
  const boxes = frameBoxes(context.window.CITY.GEO.frame, eglintonWorld);
  const snapshots = Object.fromEntries(STREET_FURNITURE.map(({name}) => [name, JSON.parse(fs.readFileSync(path.join(root,`tools/data/${name}-20261126.json`),'utf8'))]));
  for (const [frameName, frame] of Object.entries(boxes)) {
    const data = streetFurniture(snapshots, frame);
    const file = frameName === 'detail' ? 'js/toronto-street-furniture.js' : `js/frames/${frameName}/toronto-street-furniture.js`;
    fs.mkdirSync(path.dirname(path.join(root,file)), {recursive: true});
    fs.writeFileSync(path.join(root,file), `// GENERATED by tools/build-open-data.mjs. City Existing poster & publication structures (${frameName} frame) and the litter receptacle audit, dated snapshots.\n(function () { window.CITY.STREET_FURNITURE = ${JSON.stringify(data)}; })();\n`);
    console.log(`[openData] ${frameName}: ${data.posters.records.length} poster, ${data.publications.records.length} publication records; litter ${data.litter.counts.inFrame} in frame`);
  }
}
