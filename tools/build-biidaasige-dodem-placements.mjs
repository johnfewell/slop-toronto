import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const fit=JSON.parse(fs.readFileSync(path.join(root,'tools/fixtures/biidaasige-dodem-registration.json'),'utf8'));
// Captain reviewed all seven against the finished-site photo, independent bench holdout,
// aerial object cross-checks and the two actual source-traced woodchip footprints.
const accepted=new Set(['dodem-beaver','dodem-otter','dodem-wolf','dodem-bear','dodem-turtle','dodem-musky','dodem-eagle']);
const rows=fit.animals.filter(a=>accepted.has(a.id)).map(a=>({id:a.id,kind:a.kind,lat:a.bodyLat,lon:a.bodyLon,
 yaw:a.headingDegFromPlusZ*Math.PI/180,errorM:a.positionUncertaintyM,source:'MVVA finished-site photo registered to City2025 orthophoto',
 islandId:a.islandFeatureId,confidence:'captain-reviewed-photo-estimate-not-survey'}));
if(rows.length!==7||rows.some(r=>![r.lat,r.lon,r.yaw,r.errorM].every(Number.isFinite)))throw Error('Invalid reviewed Dodem poses');
const output=`// Generated by tools/build-biidaasige-dodem-placements.mjs. Source facts only; no image pixels.
// Seven captain-reviewed photo estimates, each with at least 3 m position uncertainty.
(function(){
const C=window.CITY;
const DATA=${JSON.stringify(rows)};
C.BIIDAASIGE_DODEM_SOURCE_POSES=DATA;
C.biidaasigeDodemSourcePoses=function(){
 if(typeof C.worldFromLatLon!=='function'||typeof C.biidaasigeWoodchipIslandAt!=='function')return [];
 return DATA.flatMap(r=>{
  const p=C.worldFromLatLon(r.lat,r.lon);
  if(!p||!Number.isFinite(p.x)||!Number.isFinite(p.z))return [];
  const query=r.islandId==='dodem-three-animal-island'?C.biidaasigeDodemThreeIslandAt:C.biidaasigeWoodchipIslandAt;
  const surface=typeof query==='function'?query(p.x,p.z):null;
  if(surface?.kind!=='woodchip'||!Number.isFinite(surface.surfaceY))return [];
  return [{...r,x:p.x,z:p.z,y:surface.surfaceY}];
 });
};
})();
`;
const target=path.join(root,'js/biidaasige-dodem-placements.js');
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('Dodem placements need regeneration');
 console.log('Dodem placements current (7 reviewed source poses)');
}else{fs.writeFileSync(target,output);console.log('Wrote 7 reviewed Dodem source poses');}
