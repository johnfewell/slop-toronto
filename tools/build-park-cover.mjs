// tools/build-park-cover.mjs → js/high-park-cover-data.js (docs/park-cover.md)
// High Park's shrub layer from the province's lidar, for js/park-cover.js: on the woods' 4 m grid over the park's box
// (js/high-park-woods-data.js ground), the share of each cell's ground under vegetation 1 to 5 m tall (the Digital
// Surface Model over the Digital Terrain Model, both 0.5 m, the highest of the four pixels in each 1 m cell, as
// tools/build-park-woods.mjs reads the canopy): the savanna's thickets of sumac, dogwood, serviceberry and oak sprouts,
// the young trees at the woods' edges. The tall grass and forbs are under the lidar's resolution (the meadow reads as
// bare ground): js/park-cover.js lays them where OpenStreetMap maps wood or scrub in the open (the woods data's meadow).
// Under closed canopy the first return is the canopy's, so the understory there comes from park-cover.js's own rules.
//
//   shrub = the cell's share of island ground (1 m cells, off ponds, buildings, courts and pitches as the woods build
//           has them) under 1-5 m: 2 bits, 0 under 5%, 1 under 20%, 2 under 45%, 3 more
// Usage: node tools/build-park-cover.mjs [--out js/high-park-cover-data.js]
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadCity, openDtm } from './terrain-pilot-lib.mjs';

const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const OUT = arg('--out') || path.join(ROOT, 'js/high-park-cover-data.js');
const C = loadCity(['js/high-park-data.js', 'js/high-park-woods-data.js']);
const WD = C.HIGH_PARK_WOODS_DATA, BOX = WD.box, CELL = WD.ground.cell, CW = WD.ground.w, CH = WD.ground.h;
const LO = 1, HI = 5, EDGES = [0.05, 0.2, 0.45];
const dtm = openDtm(C, BOX, 'manifest-high-park.json'), dsm = openDtm(C, BOX, 'manifest-high-park-dsm.json');
// (the woods' ground grid: 0 off the park's islands)
const gbin = Buffer.from(WD.ground.cells, 'base64'), kind = (q) => (gbin[q >> 2] >> ((q & 3) * 2)) & 3;
// (the ponds and pads: no shrub counted on them)
const off = [];
for (const [k, , flat] of C.GEO.areas) {
  if (k !== 'water' && k !== 'pitch') continue;
  const pts = []; for (let i = 0; i < flat.length; i += 2) pts.push([flat[i], flat[i + 1]]);
  if (pts.some(([x, z]) => x > BOX.x0 - 50 && x < BOX.x1 + 50 && z > BOX.z0 - 50 && z < BOX.z1 + 50)) off.push(pts);
}
const inPoly = (pts, x, z) => { let c = false; for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) { const a = pts[i], b = pts[j]; if ((a[1] > z) !== (b[1] > z) && x < ((b[0] - a[0]) * (z - a[1])) / (b[1] - a[1]) + a[0]) c = !c; } return c; };
const cells = new Uint8Array(Math.ceil((CW * CH) / 4));
const counts = [0, 0, 0, 0];
for (let cj = 0; cj < CH; cj++) for (let ci = 0; ci < CW; ci++) {
  const q = cj * CW + ci;
  if (!kind(q)) continue;
  let n = 0, s = 0;
  for (let j = 0; j < CELL; j++) for (let i = 0; i < CELL; i++) {
    const x = BOX.x0 + ci * CELL + i + 0.5, z = BOX.z0 + cj * CELL + j + 0.5;
    let m = 0;
    for (const [dx, dz] of [[-0.25, -0.25], [0.25, -0.25], [-0.25, 0.25], [0.25, 0.25]]) {
      const a = dsm.fineAt(x + dx, z + dz), b = dtm.fineAt(x + dx, z + dz);
      if (a > -100 && a < 1000 && b > -100 && b < 1000) m = Math.max(m, a - b);
    }
    n++;
    if (m >= LO && m < HI) s++;
  }
  if (!n) continue;
  const share = s / n;
  let v = share < EDGES[0] ? 0 : share < EDGES[1] ? 1 : share < EDGES[2] ? 2 : 3;
  if (v) { const x = BOX.x0 + (ci + 0.5) * CELL, z = BOX.z0 + (cj + 0.5) * CELL; if (off.some((p) => inPoly(p, x, z))) v = 0; }
  cells[q >> 2] |= v << ((q & 3) * 2);
  counts[v]++;
}
const ha = (k) => +((counts[k] * CELL * CELL) / 1e4).toFixed(1);
const data = {
  version: 1, kind: 'high-park-cover', box: BOX,
  source: { dataset: 'Ontario Elevation Mapping Program, GTA 2023 lidar: Digital Surface Model (first return) over Digital Terrain Model (bare earth), 0.5 m', licence: `${dsm.manifest.licence} (${dsm.manifest.licenceUrl}); see CREDITS.md`, attribution: dsm.manifest.attribution },
  rules: { shrubBandM: [LO, HI], shareEdges: EDGES },
  units: 'shrub: 2 bits per cell of the woods data\'s ground grid (cell m, w x h, rows along x from the box corner): 0 under 5% of the cell\'s ground under 1-5 m vegetation, 1 under 20%, 2 under 45%, 3 more',
  diagnostics: { ha: { none: ha(0), sparse: ha(1), shrubs: ha(2), thicket: ha(3) } },
  shrub: { cell: CELL, w: CW, h: CH, cells: Buffer.from(cells).toString('base64') }
};
const js = `// js/high-park-cover-data.js — GENERATED by tools/build-park-cover.mjs, do not edit by hand.
// High Park's shrub layer from the Ontario GTA 2023 lidar (Open Government Licence – Ontario; docs/park-cover.md): the share of
// each 4 m cell's ground under vegetation 1-5 m tall, for js/park-cover.js. Always loaded (explore.html).
(function () {
window.CITY = window.CITY || {};
window.CITY.HIGH_PARK_COVER_DATA = ${JSON.stringify(data)};
})();
`;
fs.writeFileSync(OUT, js);
console.log(`[park-cover] ${JSON.stringify(data.diagnostics)}`);
console.log(`[park-cover] wrote ${path.relative(ROOT, OUT)} (${(js.length / 1024).toFixed(0)} KB)`);
