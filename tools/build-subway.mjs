// tools/build-subway.mjs — writes js/toronto-subway.js (window.CITY.GEO_SUBWAY) from tools/geo-subway.mjs: the TTC
// subway's lines, stations & street entrances in the world frame. Its own file beside js/toronto-geodata.js, so the
// subway can be rebuilt without the whole city.
// usage: GEO_DATA=~/.cache/slop-toronto/osm node tools/build-subway.mjs [out.js]
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ways, stations, entrances } from './geo-subway.mjs';

const OUT = process.argv[2] || fileURLToPath(new URL('../js/toronto-subway.js', import.meta.url));
const data = { ways, stations, entrances };
fs.writeFileSync(OUT, `// js/toronto-subway.js — GENERATED by tools/build-subway.mjs, do not edit by hand.
// The TTC subway (lines, stations, street entrances) in the world frame of js/toronto-geodata.js.
// © OpenStreetMap contributors (ODbL).
(function () {
window.CITY = window.CITY || {};
window.CITY.GEO_SUBWAY = ${JSON.stringify(data)};
})();
`);
console.log(`[subway] wrote ${OUT} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
