// tools/build-shores.mjs — the shore classes the naturalistic water edges read (st-de3g; js/water-edges.js): from
// OpenStreetMap's land extract (tools/fetch-osm.mjs writes osm_land.json), the beaches (natural=beach, natural=sand,
// surface=sand / pebbles on a beach), the wetlands (natural=wetland: marsh, reedbed, swamp) and the engineered edges
// that must stay crisp (man_made=pier / quay / breakwater / groyne / embankment, barrier=wall / retaining_wall), each
// projected into the city's world metres (the geodata's frame) and kept where it lies inside the bigger map's frame.
// The data is frame-independent: js/water-edges.js classifies whichever map's own water outlines against it at load.
// usage: GEO_DATA=~/.cache/slop-toronto/osm-ids node tools/build-shores.mjs [out.js]   (default js/toronto-shores.js)
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import vm from 'node:vm';

const out = process.argv[2] || 'js/toronto-shores.js';
const dir = process.env.GEO_DATA || path.join(os.homedir(), '.cache/slop-toronto/osm-ids');
const land = JSON.parse(fs.readFileSync(path.join(dir, 'osm_land.json'), 'utf8'));

// the city's projection, as the committed geodata states it (tools/geo-base.mjs toWorld)
const ctx = vm.createContext({ window: { CITY: {} } });
vm.runInContext(fs.readFileSync('js/toronto-geodata.js', 'utf8'), ctx);
const P = ctx.window.CITY.GEO.frame.projection;
const toWorld = (lon, lat) => {
  const e = (lon - P.lon0) * P.kx, n = (lat - P.lat0) * P.ky, c = Math.cos(P.theta), s = Math.sin(P.theta);
  return [e * c - n * s - P.ox, -(e * s + n * c) - P.oz];
};
// the bigger map's frame (tools/frames/eglinton.json) and a margin: the far shores outside it are never drawn
const frames = ['tools/frames/eglinton.json'].filter((f) => fs.existsSync(f)).map((f) => JSON.parse(fs.readFileSync(f, 'utf8')));
const BOX = { x0: Infinity, x1: -Infinity, z0: Infinity, z1: -Infinity };
for (const f of frames) {
  const d = f.world || f;
  if (Number.isFinite(d.x0)) Object.assign(BOX, { x0: Math.min(BOX.x0, d.x0 - 300), x1: Math.max(BOX.x1, d.x1 + 300), z0: Math.min(BOX.z0, d.z0 - 300), z1: Math.max(BOX.z1, d.z1 + 300) });
}

const q = (v) => Math.round(v * 10) / 10;
const rings = (e) => {
  if (e.type === 'way' && e.geometry) return [e.geometry];
  if (e.type === 'relation' && e.members) return e.members.filter((m) => m.geometry && m.role !== 'inner').map((m) => m.geometry);
  return [];
};
const project = (g) => g.map((p) => toWorld(p.lon, p.lat)).flatMap(([x, z]) => [q(x), q(z)]);
const inBox = (flat) => { for (let i = 0; i < flat.length; i += 2) if (flat[i] > BOX.x0 && flat[i] < BOX.x1 && flat[i + 1] > BOX.z0 && flat[i + 1] < BOX.z1) return true; return false; };
const closed = (g) => g.length > 3 && g[0].lat === g[g.length - 1].lat && g[0].lon === g[g.length - 1].lon;

const beaches = [], wetlands = [], hard = [];
const kinds = {};
for (const e of land.elements) {
  const t = e.tags || {};
  const beach = t.natural === 'beach' || t.natural === 'sand' || (t.natural === 'shingle');
  const wet = t.natural === 'wetland';
  const hardKind = ['pier', 'quay', 'breakwater', 'groyne', 'embankment'].includes(t.man_made) ? t.man_made
    : t.barrier === 'retaining_wall' ? 'retaining_wall' : t.barrier === 'wall' ? 'wall' : null;
  if (!beach && !wet && !hardKind) continue;
  for (const g of rings(e)) {
    const flat = project(g);
    if (flat.length < 4 || !inBox(flat)) continue;
    if (beach && closed(g)) beaches.push({ s: t.natural === 'shingle' || /pebble|gravel|stone/.test(t.surface || '') ? 1 : 0, n: t.name || '', p: flat.slice(0, -2) });
    else if (wet && closed(g)) wetlands.push({ k: t.wetland || '', p: flat.slice(0, -2) });
    else if (hardKind) hard.push({ k: hardKind, a: closed(g) ? 1 : 0, p: flat });
    kinds[beach ? 'beach' : wet ? 'wetland' : hardKind] = (kinds[beach ? 'beach' : wet ? 'wetland' : hardKind] || 0) + 1;
  }
}
const data = { version: 1, source: 'OpenStreetMap (ODbL), osm_land.json', beaches, wetlands, hard };
const text = `// ${out} — GENERATED by tools/build-shores.mjs from OpenStreetMap (© OpenStreetMap contributors, ODbL). Do not edit.
// The naturalistic water edges' shore data (js/water-edges.js): beaches & sand (s 1: shingle / pebbles), wetlands and
// the engineered edges (piers, quays, breakwaters, groynes, embankments, walls), as flat [x, z, ...] world metres.
window.CITY = window.CITY || {};
window.CITY.SHORES = ${JSON.stringify(data)};
`;
fs.writeFileSync(out, text);
console.log(`${out}: ${beaches.length} beaches, ${wetlands.length} wetlands, ${hard.length} hard edges (${JSON.stringify(kinds)}), ${(text.length / 1024).toFixed(0)} KB`);
