// tools/park-woods-parks.mjs — the wooded parks tools/build-park-woods.mjs builds from the GTA 2023 lidar, one entry a
// park (docs/high-park-woods.md, docs/toronto-island-woods.md). An entry names:
//   parkNames  the islands (GEO blocks) whose invented trees the lidar's replace, by their park's name
//   box(C)     the world box the build covers (whole metres), round those islands
//   manifests  the DTM's and DSM's tile manifests (node tools/fetch-don-valley-dtm.mjs --region <id> [--product dsm])
//   lake       the box reaches open lake, where the project has no tiles (no canopy there)
//   relief     (C, box, dtm) => (x, z) => { y: height over the street level, slope }: woods under the street or on a
//              slope over 25% are the ravines'
//   mix        the shares of oak / ash / aspen by habitat (open, woods, ravine)
//   modelNames the park's own name for a model (ez-trees.js draws the variant: Toronto Island's cottonwoods)
//   out, global, header, scripts: the data file, its window.CITY name, its first lines, the city scripts the build reads
// Adding a park: an entry here, its region in tools/fetch-don-valley-dtm.mjs, and its data file's script tag before
// js/park-woods.js in explore.html.

/** High Park: the terrain pilot's box and its relief before the conditioning (DTM - datum: the roads, pads and shores
 * rules don't move a crown's habitat) */
function highParkRelief(C, BOX) {
  const HPD = C.HIGH_PARK_DATA;
  const HG = (() => { const b = Buffer.from(HPD.unconditioned, 'base64'); return new Int16Array(b.buffer, b.byteOffset, b.length / 2); })();
  const S = HPD.box.step, gnx = HPD.nx, gnz = HPD.nz;
  return (x, z) => {
    const fc = Math.max(0, Math.min(gnx - 1.0001, (x - BOX.x0) / S)), fr = Math.max(0, Math.min(gnz - 1.0001, (z - BOX.z0) / S));
    const c = Math.floor(fc), r = Math.floor(fr), tx = fc - c, tz = fr - r, k = r * gnx + c, h = (q) => HG[q] / 100;
    const y = (h(k) * (1 - tx) + h(k + 1) * tx) * (1 - tz) + (h(k + gnx) * (1 - tx) + h(k + gnx + 1) * tx) * tz;
    const gx = ((h(k + 1) - h(k)) * (1 - tz) + (h(k + gnx + 1) - h(k + gnx)) * tz) / S, gz = ((h(k + gnx) - h(k)) * (1 - tx) + (h(k + gnx + 1) - h(k + 1)) * tx) / S;
    return { y, slope: Math.hypot(gx, gz) };
  };
}

/** A park without a terrain pilot: the slope from the DTM's 10 m means 10 m apart; nothing is under the street level */
function dtmRelief(C, BOX, dtm) {
  return (x, z) => ({ y: 0, slope: Math.hypot(dtm.demAt(x + 5, z) - dtm.demAt(x - 5, z), dtm.demAt(x, z + 5) - dtm.demAt(x, z - 5)) / 10 });
}

const header = (file, by, title, doc) => `// ${file} — GENERATED by ${by}, do not edit by hand.
// ${title} from the Ontario GTA 2023 lidar (Open Government Licence – Ontario; ${doc}): each
// crown on the park's islands, where it stands, its height and width, and its habitat. Always loaded (explore.html).
`;

