// tools/build-cafeto.mjs: the CaféTO snapshot (tools/fetch-cafeto.mjs) clipped to the detailed city, as the small
// static layer js/toronto-cafeto.js. Only the sidewalk and curb lane cafés are kept as records; private property patios
// are counted and never placed. Placement itself happens in js/patio-layout.js (docs/cafeto-patios.md).
// usage: node tools/build-cafeto.mjs [snapshot.json] [output.js]
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { projectPoint } from './build-open-data.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const TYPES = { 'Sidewalk Café': 'sidewalk', 'Curb Lane Café': 'curb', 'Private Property Patio': 'private' };

// "101-103 RONCESVALLES AVE", "3 & 3A WESTMORELAND AVE", "10-12 COLLEGE ST (CONFIRMED ADDRESS: 450 YONGE ST)" -> the street
export function addressStreet(address) {
  return String(address || '').replace(/\(.*?\)/g, '').split(',')[0].trim()
    .replace(/^\d+[A-Z]?(\s*[-&/]\s*\d+[A-Z]?)*\s+/, '').trim();
}

export function cafeto(snapshot, frame) {
  if (!snapshot?.source?.resourceId || !Array.isArray(snapshot.features) || !snapshot.features.length) throw new Error('Incomplete CaféTO snapshot');
  const ids = new Set(), records = [];
  const counts = { total: 0, outside: 0, private: 0, sidewalk: 0, curb: 0 };
  for (const { properties: a, geometry } of snapshot.features) {
    counts.total++;
    const type = TYPES[a.INTERVENTION_TYPE];
    if (!type) throw new Error(`Unknown CaféTO intervention type: ${a.INTERVENTION_TYPE}`);
    const id = String(a.LICENCE_NUMBER || '').trim();
    if (!id || ids.has(id)) throw new Error(`Missing/duplicate CaféTO licence number: ${id}`);
    ids.add(id);
    const point = projectPoint(geometry, frame);
    if (!point) { counts.outside++; continue; }
    counts[type]++;
    if (type === 'private') continue;
    const proposed = String(a.PROPOSED_STREET_LOCATION || '').trim();
    records.push({
      id, type, operator: a.OPERATOR_NAME === 'None' ? '' : String(a.OPERATOR_NAME || '').trim(),
      address: String(a.MUNICIPAL_ADDRESS || '').trim(),
      street: type === 'curb' && proposed && proposed !== 'None' ? proposed : addressStreet(a.MUNICIPAL_ADDRESS),
      bia: a.BIA_NAME && a.BIA_NAME !== 'None' ? a.BIA_NAME : '', ...point
    });
  }
  records.sort((p, q) => p.id.localeCompare(q.id));
  return { source: snapshot.source, counts, records };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const context = { window: { CITY: {} } };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js/toronto-geodata.js'), 'utf8'), context);
  const input = process.argv[2] || fs.readdirSync(path.join(ROOT, 'tools/data')).filter((f) => /^cafeto-\d{8}\.json$/.test(f)).sort().map((f) => path.join(ROOT, 'tools/data', f)).pop();
  const output = process.argv[3] || path.join(ROOT, 'js/toronto-cafeto.js');
  const data = cafeto(JSON.parse(fs.readFileSync(input, 'utf8')), context.window.CITY.GEO.frame);
  fs.writeFileSync(output, '// GENERATED by tools/build-cafeto.mjs. City of Toronto CaféTO Locations, dated snapshot (Open Government Licence – Toronto).\n' +
    '// Business address points and intervention types, not patio footprints: js/patio-layout.js places them by rule.\n' +
    '(function () { window.CITY = window.CITY || {}; window.CITY.CAFETO = ' + JSON.stringify(data) + '; })();\n');
  console.log(`[cafeto] ${data.records.length} records in the detailed city; ${JSON.stringify(data.counts)}`);
}
