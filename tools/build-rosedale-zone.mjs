// tools/build-rosedale-zone.mjs (jf-qw7, docs/rosedale-streetscape.md): the area of South and North Rosedale (the two Heritage Conservation Districts) where the street furniture
// is Rosedale's: js/rosedale-zone.js (a 20 m mask, run-length coded) that js/mapped-poles.js asks "is this pole in Rosedale?".
//
// usage: node tools/build-rosedale-zone.mjs <houses.csv>
//   houses.csv  rosedale-houses/1 of the shared Toronto data repo (its `hcd` column says which houses lie in the South or North Rosedale HCD)
// The houses' world positions come from data/frames/eglinton/rosedale-houses.bin (joined on the City 3D Massing id). A cell is in the zone when it is within 34 m of the first
// corner of a house in either HCD, then the mask is closed (dilated and eroded by two cells) so the street between two houses and the lots' gaps are in. Moore Park and
// Summerhill houses (no HCD) stay out: 133 of their 1,953 houses lie inside the mask, at its edge.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { unpackGeo } from '../js/geodata-loader.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const csvFile = process.argv[2];
if (!csvFile) { console.error('usage: node tools/build-rosedale-zone.mjs <houses.csv>'); process.exit(2); }
const CELL = 20, REACH = 34, CLOSE = 2;

const buf = fs.readFileSync(ROOT + 'data/frames/eglinton/rosedale-houses.bin');
const { ROSEDALE_HOUSES: H } = await unpackGeo(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const lines = fs.readFileSync(csvFile, 'utf8').split('\n');
const head = lines[0].split(','), iId = head.indexOf('id'), iHcd = head.indexOf('hcd');
const hcd = new Map();
for (const l of lines.slice(1)) { if (!l) continue; const c = l.split(','); hcd.set(c[iId], c[iHcd]); }
const pts = [];
for (let i = 0; i < H.houses; i++) {
  const id = 'to-3dmassing-2025:' + H.fid[i] + (H.part[i] > 1 ? '.' + (H.part[i] - 1) : '');
  const z = hcd.get(id);
  if (z === 'north-rosedale' || z === 'south-rosedale') pts.push([H.start[2 * i] / H.grid, H.start[2 * i + 1] / H.grid]);
}
const x0 = Math.floor((Math.min(...pts.map((p) => p[0])) - 80) / CELL) * CELL, z0 = Math.floor((Math.min(...pts.map((p) => p[1])) - 80) / CELL) * CELL;
const W = Math.floor((Math.max(...pts.map((p) => p[0])) + 80 - x0) / CELL) + 1, Hh = Math.floor((Math.max(...pts.map((p) => p[1])) + 80 - z0) / CELL) + 1;
let g = Array.from({ length: Hh }, () => new Uint8Array(W));
for (const [x, z] of pts) {
  for (let j = Math.floor((z - REACH - z0) / CELL); j <= Math.floor((z + REACH - z0) / CELL) + 1; j++) {
    for (let i = Math.floor((x - REACH - x0) / CELL); i <= Math.floor((x + REACH - x0) / CELL) + 1; i++) {
      if (i >= 0 && i < W && j >= 0 && j < Hh && Math.hypot(x0 + (i + 0.5) * CELL - x, z0 + (j + 0.5) * CELL - z) <= REACH) g[j][i] = 1;
    }
  }
}
const morph = (src, r, want) => src.map((row, j) => row.map((_, i) => {
  let all = 1, any = 0;
  for (let dj = -r; dj <= r; dj++) for (let di = -r; di <= r; di++) {
    const v = j + dj >= 0 && j + dj < Hh && i + di >= 0 && i + di < W ? src[j + dj][i + di] : 0;
    all &= v; any |= v;
  }
  return want === 'all' ? all : any;
}));
g = morph(morph(g.map((r) => Array.from(r)), CLOSE, 'any'), CLOSE, 'all');
const rows = g.map((row) => {
  const runs = [];
  for (let i = 0; i < W;) { if (!row[i]) { i++; continue; } let k = i; while (k < W && row[k]) k++; runs.push(`${i}-${k - i}`); i = k; }
  return runs.join(' ');
});
const cells = g.reduce((a, r) => a + r.reduce((b, v) => b + v, 0), 0);
const out = `// js/rosedale-zone.js: GENERATED by tools/build-rosedale-zone.mjs (jf-qw7, docs/rosedale-streetscape.md). Do not edit.
// The ground of South and North Rosedale (the two Heritage Conservation Districts), a ${CELL} m mask over the world's x, z: ${cells} cells, ${rows.join('').length} characters.
// \`CITY.rosedaleZoneAt(x, z)\` says whether a point lies in it; js/mapped-poles.js draws a street light there as Rosedale's black globe post.
(function () {
const Z = { cell: ${CELL}, x0: ${x0}, z0: ${z0}, w: ${W}, h: ${Hh}, rows: ${JSON.stringify(rows)} };
const runs = Z.rows.map((r) => (r ? r.split(' ').map((s) => s.split('-').map(Number)) : []));
function rosedaleZoneAt(x, z) {
  const i = Math.floor((x - Z.x0) / Z.cell), j = Math.floor((z - Z.z0) / Z.cell);
  if (i < 0 || j < 0 || i >= Z.w || j >= Z.h) return false;
  for (const [a, n] of runs[j]) if (i >= a && i < a + n) return true;
  return false;
}
window.CITY = window.CITY || {};
Object.assign(window.CITY, { rosedaleZoneAt, ROSEDALE_ZONE: { cell: Z.cell, x0: Z.x0, z0: Z.z0, w: Z.w, h: Z.h } });
})();
`;
fs.writeFileSync(ROOT + 'js/rosedale-zone.js', out);
console.log(`js/rosedale-zone.js: ${W} x ${Hh} cells of ${CELL} m, ${cells} in the zone, ${(out.length / 1024).toFixed(1)} KB, from ${pts.length} HCD houses`);
