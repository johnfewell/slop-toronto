// tools/build-subway-topology.mjs — writes js/toronto-subway-topology.js (window.CITY.SUBWAY_TOPOLOGY): the subway's
// stable station / platform / direction / segment identities, their sources and the supported rides
// (tools/subway-topology.mjs, docs/subway-topology.md). Reads only committed files: js/toronto-subway.js (rebuild it
// first with tools/build-subway.mjs when the OpenStreetMap download changes), js/toronto-transit.js and
// tools/subway-station-facts.mjs. The same inputs always give the same bytes (tests/subway-topology.test.mjs).
// usage: node tools/build-subway-topology.mjs [out.js]
import fs from 'node:fs';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { buildSubwayTopology } from './subway-topology.mjs';
import { STATION_FACTS, GTFS_STATION_ALIASES, SUPPORTED_RIDES, PROFILE_LIMITS } from './subway-station-facts.mjs';

export function readInputs(root = new URL('..', import.meta.url)) {
  const context = vm.createContext({ window: { CITY: {} } });
  for (const file of ['js/toronto-subway.js', 'js/toronto-transit.js']) vm.runInContext(fs.readFileSync(new URL(file, root), 'utf8'), context);
  const { GEO_SUBWAY: subway, GEO_TRANSIT: transit } = context.window.CITY;
  return { subway, transit, facts: STATION_FACTS, aliases: GTFS_STATION_ALIASES, rides: SUPPORTED_RIDES, limits: PROFILE_LIMITS };
}

export function renderTopology(topology, transitSource) {
  return `// js/toronto-subway-topology.js — GENERATED by tools/build-subway-topology.mjs, do not edit by hand.
// The TTC subway's passenger topology (docs/subway-topology.md): stations, platforms, directions, track segments and
// the supported rides, joined from js/toronto-subway.js (© OpenStreetMap contributors, ODbL), js/toronto-transit.js
// (TTC GTFS, ${transitSource}; Open Government Licence – Toronto) and tools/subway-station-facts.mjs (TTC station pages).
(function () {
window.CITY = window.CITY || {};
window.CITY.SUBWAY_TOPOLOGY = ${JSON.stringify(topology)};
})();
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const OUT = process.argv[2] || fileURLToPath(new URL('../js/toronto-subway-topology.js', import.meta.url));
  const inputs = readInputs();
  const topology = buildSubwayTopology(inputs);
  const src = inputs.transit.source || {};
  fs.writeFileSync(OUT, renderTopology(topology, `${src.dataset || 'GTFS'} ${src.modified || ''}`.trim()));
  const s = topology.summary;
  console.log(`[subway-topology] ${topology.stations.length} stations, ${s.platforms} platforms (${s.platformsLocated} on the track, ${s.platformsRightHand} right-hand checked), ${s.segments} segments (${s.continuous} continuous), rides: ${s.rides.join(', ') || 'none'}${s.problems.length ? `; problems: ${s.problems.join('; ')}` : ''}`);
  for (const seg of topology.segments.filter((x) => !x.continuous)) console.log(`  ${seg.id}: ${seg.problem}`);
  console.log(`[subway-topology] wrote ${OUT} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
}
