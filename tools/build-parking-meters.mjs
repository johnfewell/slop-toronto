// Builds a small static layer from TPA's public machine-point snapshot, not zone/lot centroids.
// node tools/build-parking-meters.mjs [snapshot.json] [output.js]
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export function parkingMeters(snapshot, frame) {
  const { projection: p, detail: b } = frame;
  if (snapshot.installs.exceededTransferLimit || snapshot.decommissions.exceededTransferLimit) throw new Error('Incomplete TPA snapshot');
  const retired = new Set(snapshot.decommissions.features.map((f) => String(f.attributes.DG4_Machine__).trim()));
  // A few phase-4 rows reuse phase-3 IDs/coordinates with conflicting addresses.
  // Quarantine every occurrence of an ambiguous ID instead of choosing arbitrarily.
  const frequencies = new Map();
  for (const f of snapshot.installs.features) {
    const id = String(f.attributes.PBP_Machine__ || '').trim();
    frequencies.set(id, (frequencies.get(id) || 0)+1);
  }
  const records = [], rejected = { retired: 0, outside: 0, ambiguous: 0 };
  for (const feature of snapshot.installs.features) {
    const a = feature.attributes, { x: lon, y: lat } = feature.geometry || {};
    const id = String(a.PBP_Machine__ || '').trim();
    if (!id || !Number.isFinite(lon) || !Number.isFinite(lat) || lon < -80 || lon > -79 || lat < 43 || lat > 44) throw new Error(`Invalid machine point ${id}`);
    if (frequencies.get(id) > 1) { rejected.ambiguous++; continue; }
    if (retired.has(String(a.DG4_Machine__).trim())) { rejected.retired++; continue; }
    const e = (lon-p.lon0)*p.kx, n = (lat-p.lat0)*p.ky;
    const x = e*Math.cos(p.theta)-n*Math.sin(p.theta)-p.ox;
    const z = -(e*Math.sin(p.theta)+n*Math.cos(p.theta))-p.oz;
    if (x <= b.x0 || x >= b.x1 || z <= b.z0 || z >= b.z1) { rejected.outside++; continue; }
    records.push({ id, zone: String(a.Location_ID), address: a.SAP_Address, phase: a.Phase, x: Math.round(x*10)/10, z: Math.round(z*10)/10 });
  }
  records.sort((a,b) => a.id.localeCompare(b.id));
  return { source: snapshot.source, fetchedAt: snapshot.fetchedAt, sourceUpdatedAt: snapshot.sourceUpdatedAt, rejected, records };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const context = { window: { CITY: {} } };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js/toronto-geodata.js'), 'utf8'), context);
  const input = process.argv[2] || path.join(ROOT, 'tools/data/parking-meters-20261028.json');
  const output = process.argv[3] || path.join(ROOT, 'js/toronto-parking-meters.js');
  const data = parkingMeters(JSON.parse(fs.readFileSync(input, 'utf8')), context.window.CITY.GEO.frame);
  fs.writeFileSync(output, '// GENERATED by tools/build-parking-meters.mjs. TPA public S5 machine snapshot; not live operational status.\n'+
    '(function () { window.CITY = window.CITY || {}; window.CITY.PARKING_METERS = '+JSON.stringify(data)+'; })();\n');
  console.log(`[parkingMeters] ${data.records.length} machine records; ${JSON.stringify(data.rejected)}`);
}
