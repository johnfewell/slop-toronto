(function () {
// js/waterfront-island-buildings.js
// Conservative, source-matched rendering profiles for the Toronto Islands (st-sb3r.16). The committed geodata rows
// on the island carry inherited generic mid/high-rise heights over one- and two-storey Ward's/Algonquin cottages and
// small park buildings, so js/buildings.js draws them as urban towers. This module does NOT replace or move any
// building: it returns per-row rendering overrides ({ height, kind, roof, ... }) that the captain applies to the
// committed row before js/buildings.js destructures it. Footprints, colliders and GEO are never mutated, and the
// existing native instancing/weather/facade renderer is retained.
//
// Data: js/waterfront-island-buildings-data.js (generated by tools/build-island-buildings.mjs from OpenStreetMap
// footprints + tags, ODbL, the mapped Billy Bishop airport relation 85471, the Ward's/Algonquin residential landuse
// polygons, and the committed GEO.waterMask). Every record names the OSM way it came from. Explicit OSM
// height/building:levels always win (no cap); unnamed buildings use conservative estimates. The airport, the mainland
// and the Gibraltar Point Lighthouse (OSM ways 878933152 / 892934946) are excluded, so they are never overridden.
//
// Frames: records are keyed by the committed row's world centre, not by array index. The detail and Eglinton frames
// share one projection and the same footprints, so the same row resolves in either frame; outside any supported frame
// the function is a no-op (null).

const C = window.CITY || (window.CITY = {});

function data() {
  return C.ISLAND_BUILDINGS_DATA || null;
}

function frameCovers(x, z) {
  const f = C.GEO && C.GEO.frame && (C.GEO.frame.detail || C.GEO.frame);
  if (!f) return false;
  return x >= f.x0 && x <= f.x1 && z >= f.z0 && z <= f.z1;
}

// The data was built in one exact projection. Comparing only bounds is not enough: a different frame could reuse the
// same numeric centres. Every projection parameter must match the recorded one.
function projectionMatches() {
  const D = data();
  const expected = D && D.summary && D.summary.projection;
  const actual = C.GEO && C.GEO.frame && C.GEO.frame.projection;
  if (!expected || !actual) return false;
  for (const k of ['lat0', 'lon0', 'kx', 'ky', 'theta', 'ox', 'oz']) {
    const a = actual[k], e = expected[k];
    if (!Number.isFinite(a) || !Number.isFinite(e)) return false;
    if (Math.abs(a - e) > 1e-9 * Math.max(1, Math.abs(e))) return false;
  }
  return true;
}

// The committed footprint identity: yaw + part rectangles. A row that has been re-cut, moved or reshaped no longer
// matches the record even if its rounded centre still does.
function footprintMatches(row, rec) {
  if (typeof rec.fp !== 'string') return false;
  const fp = JSON.stringify([Math.round(row[2] * 1000) / 1000, row[3].map((p) => p.map((v) => Math.round(v * 10) / 10))]);
  return fp === rec.fp;
}

// The reviewed marina outliers are bound to the 2025 City 3D Massing edition. A record whose own massing edition is not
// the recorded one is inert, so a future edition (or a hand-edited record) can never silently reuse these overrides.
const REVIEWED_MASSING_EDITION = '3DMassingShapefile_2025_WGS84';
function massingEditionMatches(rec) {
  if (!rec.massing || !rec.massing.id) return true; // OSM-attributed, non-reviewed records carry no massing block
  return rec.massing.edition === REVIEWED_MASSING_EDITION;
}

function index() {
  const D = data();
  if (!D || D.error || !Array.isArray(D.records)) return null;
  if (D._index) return D._index;
  const map = new Map();
  // `records` are OSM-attributed; `massingRecords` are the reviewed City-3D-Massing-only rows (no fabricated OSM way).
  // A row centre is unique, so a later duplicate never overwrites the first.
  for (const r of [...D.records, ...(Array.isArray(D.massingRecords) ? D.massingRecords : [])]) {
    if (!Number.isFinite(r.cx) || !Number.isFinite(r.cz)) continue;
    const key = `${r.cx.toFixed(1)},${r.cz.toFixed(1)}`;
    if (!map.has(key)) map.set(key, r);
  }
  D._index = map;
  return map;
}

function islandBuildingsSupported() {
  const D = data();
  const massing = D && Array.isArray(D.massingRecords) ? D.massingRecords : [];
  return !!(D && !D.error && ((Array.isArray(D.records) && D.records.length) || massing.length) && C.GEO
    && Array.isArray(C.GEO.buildings) && projectionMatches());
}

/**
 * Pure per-row lookup. `row` is the committed GEO building row ([cx, cz, yaw, parts, height, kind, roof, seed, ?, name]);
 * `rowIndex` is accepted for callers that want to log it but is not used for identity (frames reorder rows).
 *
 * Returns null when the row is not a confirmed source-matched island building, when GeoJSON/GEO is unsupported, or when
 * the row is outside the active frame. Otherwise returns an override object with only the keys the source supports:
 *   { height, kind, roof, category, heightSource, osm, massing, marina, appearance, matchM }
 * `roof` may be null, meaning "keep the native roof" (the source did not specify a roof shape and the typology is not a
 * confirmed cottage). `osm` is null for a reviewed City-massing-only row (it carries `massing` instead).
 */
function islandBuildingProfile(row, rowIndex = -1) {
  if (!Array.isArray(row) || row.length < 4 || !Array.isArray(row[3])) return null;
  const I = index();
  if (!I) return null;
  const cx = row[0], cz = row[1];
  if (!Number.isFinite(cx) || !Number.isFinite(cz) || !frameCovers(cx, cz) || !projectionMatches()) return null;
  const rec = I.get(`${cx.toFixed(1)},${cz.toFixed(1)}`);
  if (!rec || !footprintMatches(row, rec) || !massingEditionMatches(rec)) return null;
  const profile = {
    height: rec.height,
    kind: rec.kind,
    category: rec.category,
    heightSource: rec.heightSource,
    // Appearance metadata for the scoped island renderer (js/buildings.js). Absent on older records, so callers must
    // treat every field as optional. `typology === 'cottage'` is the only gate for the cottage extension.
    typology: rec.typology || null,
    roofType: rec.roofType || null,
    roofSource: rec.roofSource || null,
    siding: rec.siding || null,
    sidingSource: rec.sidingSource || null,
    entry: rec.entry || null,
    entrySource: rec.entrySource || null,
    // Provenance: an OSM-attributed record names its way; a reviewed City-massing-only row has `osm: null` and
    // instead carries the massing record id and marina way. Neither is fabricated for the other.
    osm: rec.osm ? { ...rec.osm } : null,
    massing: rec.massing ? { ...rec.massing } : null,
    marina: rec.marina ? { ...rec.marina } : null,
    appearance: rec.appearance ? { ...rec.appearance } : null,
    matchM: rec.matchM ?? null,
    native: { ...rec.native }
  };
  if (rec.roof === 0 || rec.roof === 1) profile.roof = rec.roof;
  else profile.roof = null;
  return profile;
}

function islandBuildingsSummary() {
  const D = data();
  return D && D.summary ? D.summary : null;
}

Object.assign(C, {
  islandBuildingProfile,
  islandBuildingsSupported,
  islandBuildingsSummary
});
})();
