(function () {
// js/waterfront-island-cottage-footprint.js
// ONE source-correct effective footprint for a single confirmed Toronto Islands cottage (bead st-sb3r.32), the bounded
// pilot from docs/waterfront-island-cottage-footprint.md. The audit (docs/waterfront-island-cottage-footprint-audit.md)
// found OSM way 487167567 (7 Nottawa Avenue) is a near-rectangular mapped outline (rectangularity 0.9985) that the
// committed row renders at only 0.545 of its source area, because the native row carries a much smaller box. This
// module returns the mapped polygon's axis-aligned min-bounds in the row's OWN yaw frame and native centre, so the same
// rectangle can drive the walls, roof, trim and the OBB collider instead of a visual-only overlay.
//
// It is a PURE per-row lookup and a no-op everywhere else. It NEVER mutates GEO, the committed rows, the accepted
// profiles, or the colliders; the caller (js/buildings.js, captain-owned) applies the returned parts. The original
// committed footprint is the identity guard: a row that was re-cut, moved, reshaped, resolved in a different projection,
// is not the source-bound cottage, or whose accepted profile is missing is refused and the native parts are kept.
//
// Data: js/waterfront-island-cottage-footprint-data.js (generated by tools/build-island-cottage-footprint-pilot.mjs from
// the cached OpenStreetMap footprint the island build matched against, ODbL 1.0, and the committed geodata row). Load
// order (captain wires explore.html): the data module, this module and js/waterfront-island-buildings.js (the source
// binding this reads at call time) all before js/buildings.js. Absent the data or on a mismatched frame, every call
// returns null / the native parts.

const C = window.CITY || (window.CITY = {});

function data() {
  return C.ISLAND_COTTAGE_FOOTPRINT_DATA || null;
}

const within = (f, x, z) => !!f && x >= f.x0 && x <= f.x1 && z >= f.z0 && z <= f.z1;

function frameCovers(x, z) {
  const D = data();
  const built = D && D.summary && D.summary.frame;
  const active = C.GEO && C.GEO.frame && (C.GEO.frame.detail || C.GEO.frame);
  // REQUIRE BOTH frames. The sidecar was built for the recorded frame; the active frame may be cropped tighter while
  // sharing the same projection (the Eglinton/detail variants do), so a built-only test would claim a row outside the
  // active bounds. This never widens a record's reach: it only refuses more.
  return within(built, x, z) && within(active, x, z);
}

// The data was built in one exact projection. Bounds alone are not enough: a different frame could reuse the same
// numeric centres, so every projection parameter must match the recorded one (as js/waterfront-island-buildings.js).
function projectionMatches() {
  const D = data();
  const expected = D && D.summary && D.summary.projection;
  const actual = C.GEO && C.GEO.frame && C.GEO.frame.projection;
  if (!expected || !actual) return false;
  for (const k of ['lat0', 'lon0', 'kx', 'ky', 'theta', 'ox', 'oz']) {
    const a = actual[k], e = expected[k];
    if (!Number.isFinite(a) || !Number.isFinite(e)) return false;
    if (Math.abs(a - e) > 1e-9 * Math.max(1, Math.abs(e))) return false;
  }
  return true;
}

// The committed footprint identity: yaw + part rectangles, the same guard the island profiles use. A row that has been
// re-cut, moved or reshaped no longer matches the pilot record even if its rounded centre still does.
function nativeFootprintMatches(row, rec) {
  if (typeof rec.nativeFp !== 'string') return false;
  const fp = JSON.stringify([Math.round(row[2] * 1000) / 1000, row[3].map((p) => p.map((v) => Math.round(v * 10) / 10))]);
  return fp === rec.nativeFp;
}

function index() {
  const D = data();
  if (!D || D.error || !Array.isArray(D.records)) return null;
  if (D._index) return D._index;
  const map = new Map();
  for (const r of D.records) {
    if (!Number.isFinite(r.cx) || !Number.isFinite(r.cz)) continue;
    map.set(`${r.cx.toFixed(1)},${r.cz.toFixed(1)}`, r);
  }
  D._index = map;
  return map;
}

function islandCottageFootprintSupported() {
  const D = data();
  return !!(D && !D.error && Array.isArray(D.records) && D.records.length && C.GEO && Array.isArray(C.GEO.buildings)
    && projectionMatches());
}

/**
 * Pure per-row lookup. `row` is a committed GEO building row ([cx, cz, yaw, parts, ...]).
 *
 * Returns null unless ALL of these hold: the record's projection matches the active frame; the row's world centre is
 * covered by the frame and indexed; the row still carries the ORIGINAL footprint signature the pilot recorded; the
 * accepted island profile resolves the row as a confirmed `cottage`; and that profile is bound to the same OSM way.
 * Then it returns the source-correct effective rectangle plus its provenance:
 *   { parts, sourceID, osm, nativeParts, areas, envelope, shape, matchM, provenance }
 * `parts` are [u0, u1, v0, v1] rectangles in the row's own yaw frame and native centre, exactly as GEO rows draw them.
 */
function islandCottageFootprintProfile(row, rowIndex = -1) {
  if (!Array.isArray(row) || row.length < 4 || !Array.isArray(row[3]) || !row[3].length) return null;
  const I = index();
  if (!I) return null;
  const cx = row[0], cz = row[1];
  if (!Number.isFinite(cx) || !Number.isFinite(cz) || !frameCovers(cx, cz) || !projectionMatches()) return null;
  const rec = I.get(`${cx.toFixed(1)},${cz.toFixed(1)}`);
  if (!rec || !Array.isArray(rec.parts) || !rec.parts.length) return null;
  if (!nativeFootprintMatches(row, rec)) return null;
  // Source binding + confirmed cottage: the accepted island profile must resolve this very row AND name the same way.
  const prof = typeof C.islandBuildingProfile === 'function' ? C.islandBuildingProfile(row, rowIndex) : null;
  if (!prof || prof.typology !== 'cottage' || !prof.osm || prof.osm.id !== rec.osm.id) return null;
  return {
    parts: rec.parts.map((p) => p.slice()),
    sourceID: rec.osm.id,
    osm: { ...rec.osm },
    nativeParts: (rec.nativeParts || row[3]).map((p) => p.slice()),
    areas: rec.areas ? { ...rec.areas } : null,
    envelope: rec.shape && rec.shape.envelope ? { ...rec.shape.envelope } : null,
    shape: rec.shape ? { rectangularity: rec.shape.rectangularity, axisErrDeg: rec.shape.axisErrDeg } : null,
    matchM: rec.matchM,
    provenance: data().summary && data().summary.source ? { ...data().summary.source } : null
  };
}

/** The effective parts for a row, or null when the row is not the guarded pilot cottage (callers then keep row[3]). */
function islandCottageFootprintParts(row, rowIndex = -1) {
  const p = islandCottageFootprintProfile(row, rowIndex);
  return p ? p.parts : null;
}

/**
 * Source-guarded point test for spatial consumers (tree keep-outs, yard classification, line-of-sight). For the pilot
 * cottage it tests the EFFECTIVE rectangle; for every other row it tests that row's own native parts, so a caller can
 * route GEO.buildings through this helper unchanged and only the pilot row differs. `x, z` are world coordinates.
 */
function islandCottageFootprintAt(row, x, z) {
  if (!Array.isArray(row) || row.length < 4 || !Array.isArray(row[3])) return false;
  if (!Number.isFinite(x) || !Number.isFinite(z)) return false;
  const p = islandCottageFootprintProfile(row);
  const parts = p ? p.parts : row[3];
  const [cx, cz, ang] = row;
  const cs = Math.cos(ang), sn = Math.sin(ang);
  const dx = x - cx, dz = z - cz;
  const u = dx * cs - dz * sn, v = dx * sn + dz * cs;
  for (const [u0, u1, v0, v1] of parts) if (u > u0 && u < u1 && v > v0 && v < v1) return true;
  return false;
}

function islandCottageFootprintSummary() {
  const D = data();
  return D && D.summary ? D.summary : null;
}

Object.assign(C, {
  islandCottageFootprintProfile,
  islandCottageFootprintParts,
  islandCottageFootprintAt,
  islandCottageFootprintSupported,
  islandCottageFootprintSummary
});
})();
